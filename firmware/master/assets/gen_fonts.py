#!/usr/bin/env python3
"""
Embed Roboto (Apache 2.0) for LVGL's TinyTTF renderer.

Subsets each weight to Latin-1 + common punctuation (umlauts, ·, –, ™, …)
and writes ui/ui_fonts_data.c. Default source: the Roboto TTFs shipped with
Ubuntu (fonts-roboto); pass --dir to use others.
"""
import argparse, io, os
from fontTools import subset
from fontTools.ttLib import TTFont

WEIGHTS = {"regular": "Roboto-Regular.ttf", "medium": "Roboto-Medium.ttf", "bold": "Roboto-Bold.ttf"}
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2122, 0x20AC, 0x2192, 0x00B7]

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="/usr/share/fonts/truetype/roboto/unhinted/RobotoTTF")
ap.add_argument("--out", default="../ui/ui_fonts_data.c")
a = ap.parse_args()

with open(a.out, "w") as f:
    f.write("/* Generated by assets/gen_fonts.py. Roboto, Apache License 2.0. Do not edit. */\n")
    f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
    for key, fn in WEIGHTS.items():
        font = TTFont(os.path.join(a.dir, fn))
        opts = subset.Options()
        opts.layout_features = ["kern"]
        opts.hinting = False
        opts.name_IDs = []
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=UNICODES)
        sub.subset(font)
        buf = io.BytesIO()
        font.save(buf)
        data = buf.getvalue()
        f.write(f"const uint8_t ui_ttf_{key}[] = {{\n")
        for i in range(0, len(data), 24):
            f.write("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
        f.write(f"}};\nconst size_t ui_ttf_{key}_size = sizeof ui_ttf_{key};\n\n")
        print(key, len(data), "bytes")
